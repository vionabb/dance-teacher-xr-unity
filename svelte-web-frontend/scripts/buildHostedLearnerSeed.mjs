#!/usr/bin/env node
/**
 * Writes SQL that adds the reference dances in dances.json and their
 * segmentation trees in dancetrees.json to a hosted database's motion_video
 * and motion_video_segmentation tables (created by
 * supabase/migrations/20261121203000_hosted_learner_tables.sql).
 *
 * It mirrors scripts/syncBundleData.js, but as SQL to paste into the Supabase
 * SQL editor (no service-role key needed) and with the storage names the hosted
 * buckets hold (`<stem>.pose2d.csv`, `<stem>.holisticdata.csv`; the app tries
 * the `.raw.csv` name first and falls back to these).
 *
 * The SQL is safe to run again: a dance is added only when its video is in the
 * sourcevideos bucket and no row has the same video_src, and a tree only when
 * that dance has no tree with the same name. It ends by listing what it added
 * and which dances were skipped for a missing video.
 *
 * Usage: node scripts/buildHostedLearnerSeed.mjs [--dances <path>] [--trees <path>] > seed.sql
 */
import fs from 'node:fs';

function arg(name, fallback) {
	const i = process.argv.indexOf(name);
	return i === -1 ? fallback : process.argv[i + 1];
}

const dances = JSON.parse(
	fs.readFileSync(arg('--dances', 'src/lib/data/bundle/dances.json'), 'utf8')
);
const trees = JSON.parse(
	fs.readFileSync(arg('--trees', 'src/lib/data/bundle/dancetrees.json'), 'utf8')
);

const danceRows = dances.map((dance) => ({
	display_name: dance.title,
	video_src: dance.clipPath,
	thumbnail_src: dance.thumbnailSrc,
	height: dance.height,
	width: dance.width,
	video_duration: dance.duration,
	motion_start: dance.startTime,
	motion_end: dance.endTime,
	fps: dance.fps,
	detected_bpm: dance.bpm || null,
	detected_bpm_offset: dance.beat_offset || null,
	manual_bpm: dance.manualBPM || null,
	landmarks_pose_2d_src: `${dance.clipRelativeStem}.pose2d.csv`,
	landmarks_holistic_3d_src: `${dance.clipRelativeStem}.holisticdata.csv`
}));

const videoSrcByStem = new Map(dances.map((dance) => [dance.clipRelativeStem, dance.clipPath]));
const treeRows = [];
for (const [stem, stemTrees] of Object.entries(trees)) {
	const videoSrc = videoSrcByStem.get(stem);
	if (!videoSrc) {
		console.error(`No dance in dances.json for tree key ${stem}; skipped.`);
		continue;
	}
	for (const tree of stemTrees) {
		treeRows.push({
			video_src: videoSrc,
			display_name: tree.tree_name || 'default tree name',
			generation_info: JSON.stringify(tree.generation_data || {}),
			data: tree
		});
	}
}

function literal(value) {
	const json = JSON.stringify(value);
	let tag = 'seed';
	while (json.includes(`$${tag}$`)) tag += '_';
	return `$${tag}$${json}$${tag}$::jsonb`;
}

process.stdout
	.write(`-- Reference dances for the learner app, generated by scripts/buildHostedLearnerSeed.mjs
-- from dances.json (${danceRows.length} dances) and dancetrees.json (${treeRows.length} trees).
-- The SQL editor runs the whole script as one transaction; the last query lists what changed.
drop table if exists pg_temp.seed_report;
create temporary table seed_report (step text, detail text);

with src as (
  select * from jsonb_to_recordset(${literal(danceRows)}) as x(
    display_name text, video_src text, thumbnail_src text, height integer, width integer,
    video_duration double precision, motion_start double precision, motion_end double precision,
    fps double precision, detected_bpm double precision, detected_bpm_offset double precision,
    manual_bpm double precision, landmarks_pose_2d_src text, landmarks_holistic_3d_src text)
), skipped as (
  insert into seed_report
  select 'dance skipped: video not in sourcevideos', src.video_src from src
  where not exists (select 1 from storage.objects o where o.bucket_id = 'sourcevideos' and o.name = src.video_src)
), added as (
  insert into public.motion_video (display_name, video_src, thumbnail_src, height, width, video_duration,
    motion_start, motion_end, fps, detected_bpm, detected_bpm_offset, manual_bpm,
    landmarks_pose_2d_src, landmarks_holistic_3d_src)
  select display_name, video_src, thumbnail_src, height, width, video_duration,
    motion_start, motion_end, fps, detected_bpm, detected_bpm_offset, manual_bpm,
    landmarks_pose_2d_src, landmarks_holistic_3d_src
  from src
  where exists (select 1 from storage.objects o where o.bucket_id = 'sourcevideos' and o.name = src.video_src)
    and not exists (select 1 from public.motion_video m where m.video_src = src.video_src)
  returning video_src
)
insert into seed_report select 'dance added', video_src from added;

with src as (
  select * from jsonb_to_recordset(${literal(treeRows)}) as x(
    video_src text, display_name text, generation_info text, data jsonb)
), added as (
  insert into public.motion_video_segmentation (video_id, display_name, generation_info, data)
  select m.id, src.display_name, src.generation_info, src.data
  from src join public.motion_video m on m.video_src = src.video_src
  where not exists (
    select 1 from public.motion_video_segmentation s
    where s.video_id = m.id and s.display_name = src.display_name)
  returning display_name
)
insert into seed_report select 'tree added', display_name from added;

select step, count(*) as count, string_agg(detail, ', ' order by detail) as details
from seed_report group by step order by step;
`);
