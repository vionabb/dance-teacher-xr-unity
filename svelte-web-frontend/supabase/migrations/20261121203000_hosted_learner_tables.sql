-- Learner app tables for the hosted project.
--
-- The hosted project was set up for research and never got the learner tables
-- that the first migrations create locally (motion_video and friends), so the
-- learner menu showed no dances there. This migration brings the hosted schema
-- to the same final state as 20250828200742 + 20250911152815 + 20250911154134 +
-- 20251003130233, with two deliberate differences:
--   * anon gets read access to the catalogue only; learner tables are for
--     signed-in users (RLS limits each user to their own rows, as locally);
--   * the local catch-all storage policy "Allow access to all public buckets"
--     (SELECT on every bucket except userPerformanceVideos) is NOT recreated:
--     on hosted it would expose the private research-chi25 bucket. Hosted
--     already has a policy limited to public buckets.
--
-- Every statement is idempotent, so on a local database (where the earlier
-- migrations already created these objects) it changes only grants.
-- Rows come separately from dances.json / dancetrees.json; see
-- documentation/pwa.md ("Dances on the hosted site").

-- Catalogue: reference dances and their segmentation trees.
create table if not exists public.motion_video (
    id bigint generated always as identity,
    display_name text not null,
    uploader uuid,
    created_at timestamp with time zone default now() not null,
    video_src text not null,
    thumbnail_src text not null,
    height integer not null,
    width integer not null,
    video_duration double precision not null,
    motion_start double precision not null,
    motion_end double precision not null,
    fps double precision not null,
    detected_bpm double precision,
    detected_bpm_offset double precision,
    manual_bpm double precision,
    landmarks_pose_2d_src text,
    landmarks_holistic_3d_src text,
    constraint motion_video_pkey primary key (id),
    constraint motion_video_uploader_fkey foreign key (uploader) references public.profiles (id)
);

create table if not exists public.motion_video_segmentation (
    id bigint generated always as identity,
    created_at timestamp with time zone default now() not null,
    video_id bigint,
    display_name text,
    generation_info text not null,
    data jsonb not null,
    created_for uuid,
    constraint motion_segmentation_pkey primary key (id),
    constraint "motion_segmentation_videoId_fkey" foreign key (video_id)
        references public.motion_video (id) on update cascade on delete cascade,
    constraint "motion_segmentation_createdFor_fkey" foreign key (created_for)
        references public.profiles (id) on update cascade on delete cascade
);

-- Per-user learning state, practice attempts and coaching actions.
create table if not exists public.user_learning_model (
    id uuid default gen_random_uuid() not null,
    user_id uuid,
    video_id bigint,
    segmentation_id bigint,
    created_at timestamp without time zone default now() not null,
    updated_at timestamp without time zone default now() not null,
    plan jsonb not null,
    progress jsonb not null,
    constraint motion_userstate_pkey primary key (id),
    constraint motion_userstate_user_id_video_id_segmentation_id_key unique (user_id, video_id, segmentation_id),
    constraint motion_userstate_user_id_fkey foreign key (user_id) references public.profiles (id),
    constraint motion_userstate_video_id_fkey foreign key (video_id) references public.motion_video (id),
    constraint motion_userstate_segmentation_id_fkey foreign key (segmentation_id)
        references public.motion_video_segmentation (id)
);

create table if not exists public.user_performance_attempt (
    id bigint generated by default as identity,
    created_at timestamp with time zone default now() not null,
    user_id uuid not null,
    motion_id bigint not null,
    learningmodel_id uuid not null,
    evaluation jsonb not null,
    self_report jsonb not null,
    practice_context jsonb not null,
    duration_secs double precision,
    consecutive_attempt_number integer default 1 not null,
    previous_attempt bigint,
    video_recording_storagepath text,
    constraint user_performance_attempt_pkey primary key (id),
    constraint user_performance_attempt_previous_attempt_fkey foreign key (previous_attempt)
        references public.user_performance_attempt (id) on update cascade on delete set null,
    constraint user_performance_attempt_learningmodel_id_fkey foreign key (learningmodel_id)
        references public.user_learning_model (id) on update cascade on delete cascade,
    constraint user_performance_attempt_motion_id_fkey foreign key (motion_id)
        references public.motion_video (id) on update cascade on delete cascade,
    constraint user_performance_attempt_user_id_fkey foreign key (user_id)
        references public.profiles (id) on update cascade on delete cascade
);

create table if not exists public.ai_postperformance_action (
    id bigint generated always as identity,
    created_at timestamp with time zone default now() not null,
    action_name text not null,
    data jsonb not null,
    practice_attempt bigint not null,
    constraint ai_postperformance_action_pkey primary key (id),
    constraint ai_postperformance_action_practice_attempt_key unique (practice_attempt),
    constraint ai_postperformance_action_practice_attempt_fkey foreign key (practice_attempt)
        references public.user_performance_attempt (id) on update cascade on delete cascade
);

alter table public.motion_video enable row level security;
alter table public.motion_video_segmentation enable row level security;
alter table public.user_learning_model enable row level security;
alter table public.user_performance_attempt enable row level security;
alter table public.ai_postperformance_action enable row level security;

-- Server-generated ids, as in the local migrations.
create or replace function public.prevent_user_supplied_id_user_learning_model()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
    if tg_op = 'INSERT' and new.id is not null then
        new.id = gen_random_uuid();
    end if;
    return new;
end;
$$;

drop trigger if exists prevent_user_supplied_id_user_learning_model_trigger on public.user_learning_model;
create trigger prevent_user_supplied_id_user_learning_model_trigger
    before insert on public.user_learning_model
    for each row execute function public.prevent_user_supplied_id_user_learning_model();

create or replace function public.enforce_id_ai_postperformance_action()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
    if tg_op = 'INSERT' then
        if new.id is not null then
            new.id := nextval(pg_get_serial_sequence('public.ai_postperformance_action', 'id'));
        end if;
    elsif tg_op = 'UPDATE' then
        if new.id is distinct from old.id then
            new.id := old.id;
        end if;
    end if;
    return new;
end;
$$;

drop trigger if exists enforce_id_ai_postperformance_action_ins on public.ai_postperformance_action;
create trigger enforce_id_ai_postperformance_action_ins
    before insert on public.ai_postperformance_action
    for each row execute function public.enforce_id_ai_postperformance_action();

drop trigger if exists enforce_id_ai_postperformance_action_upd on public.ai_postperformance_action;
create trigger enforce_id_ai_postperformance_action_upd
    before update of id on public.ai_postperformance_action
    for each row execute function public.enforce_id_ai_postperformance_action();

-- Row level security: the catalogue is readable when unassigned or your own;
-- learning state and attempts only by their owner.
drop policy if exists "Allow users to select unassigned or their own motion videos" on public.motion_video;
create policy "Allow users to select unassigned or their own motion videos" on public.motion_video
    for select using (uploader is null or uploader = (select auth.uid()));

drop policy if exists "Allow access to motion segmentations for own or unassigned" on public.motion_video_segmentation;
create policy "Allow access to motion segmentations for own or unassigned" on public.motion_video_segmentation
    for select using (created_for is null or created_for = (select auth.uid()));

drop policy if exists "Enable users to read their own user models" on public.user_learning_model;
create policy "Enable users to read their own user models" on public.user_learning_model
    for select using ((select auth.uid()) = user_id);
drop policy if exists "Enable users to insert their own user models" on public.user_learning_model;
create policy "Enable users to insert their own user models" on public.user_learning_model
    for insert with check ((select auth.uid()) = user_id);
drop policy if exists "Enable users to update their own user models" on public.user_learning_model;
create policy "Enable users to update their own user models" on public.user_learning_model
    for update using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);
drop policy if exists "Enable users to delete their own user models" on public.user_learning_model;
create policy "Enable users to delete their own user models" on public.user_learning_model
    for delete using ((select auth.uid()) = user_id);

drop policy if exists "Enable users to read their own performance attempts" on public.user_performance_attempt;
create policy "Enable users to read their own performance attempts" on public.user_performance_attempt
    for select using ((select auth.uid()) = user_id);
drop policy if exists "Enable users to insert their own performance attempts" on public.user_performance_attempt;
create policy "Enable users to insert their own performance attempts" on public.user_performance_attempt
    for insert with check ((select auth.uid()) = user_id);
drop policy if exists "Enable users to update their own performance attempts" on public.user_performance_attempt;
create policy "Enable users to update their own performance attempts" on public.user_performance_attempt
    for update using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);

-- ai_postperformance_action keeps RLS on with no policies (service role only), as locally.

-- Grants: catalogue readable by everyone, learner tables by signed-in users.
revoke all on public.motion_video, public.motion_video_segmentation, public.user_learning_model,
    public.user_performance_attempt, public.ai_postperformance_action from anon, authenticated;
grant select on public.motion_video, public.motion_video_segmentation to anon, authenticated;
grant select, insert, update, delete on public.user_learning_model to authenticated;
grant select, insert, update on public.user_performance_attempt to authenticated;
grant usage, select on sequence public.user_performance_attempt_id_seq to authenticated;
grant all on public.motion_video, public.motion_video_segmentation, public.user_learning_model,
    public.user_performance_attempt, public.ai_postperformance_action to service_role;
revoke all on function public.prevent_user_supplied_id_user_learning_model() from public, anon, authenticated;
revoke all on function public.enforce_id_ai_postperformance_action() from public, anon, authenticated;

-- Practice recordings: a private bucket where each user reads, adds and
-- deletes only their own files.
insert into storage.buckets (id, name, public)
values ('userPerformanceVideos', 'userPerformanceVideos', false)
on conflict (id) do nothing;

drop policy if exists "Users can access their own performance videos" on storage.objects;
create policy "Users can access their own performance videos" on storage.objects
    for select using (bucket_id = 'userPerformanceVideos' and (select auth.uid()) = owner);
drop policy if exists "Users can upload their own performance videos" on storage.objects;
create policy "Users can upload their own performance videos" on storage.objects
    for insert with check (bucket_id = 'userPerformanceVideos' and (select auth.uid()) = owner);
drop policy if exists "Users can delete their own performance videos" on storage.objects;
create policy "Users can delete their own performance videos" on storage.objects
    for delete using (bucket_id = 'userPerformanceVideos' and (select auth.uid()) = owner);
